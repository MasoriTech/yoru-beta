const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  relaunchNoGpu: () => ipcRenderer.send('relaunch-no-gpu'),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  onSettings: (cb) => ipcRenderer.on('settings', (_e, s) => cb(s)),
  onPlayEmote: (cb) => ipcRenderer.on('play-emote', (_e, id) => cb(id)),
  onAiReply: (cb) => ipcRenderer.on('ai-reply', (_e, res) => cb(res)),
  onAiStream: (cb) => ipcRenderer.on('ai-stream', (_e, ev) => cb(ev)),
  onSpeakTest: (cb) => ipcRenderer.on('speak-test', (_e, t) => cb(t)),
  onStopSpeak: (cb) => ipcRenderer.on('stop-speak', () => cb()),
  onVoiceOrb: (cb) => ipcRenderer.on('voice-orb', (_e, st) => cb(st)),
  onCursor: (cb) => ipcRenderer.on('cursor-pos', (_e, c) => cb(c)),
  physGrab: () => ipcRenderer.send('phys-grab'),
  grabState: (on) => ipcRenderer.send('avatar-grab', !!on),
  reportHead: (x, y, r) => ipcRenderer.send('avatar-head', x, y, r),
  drop: (vx, vy) => ipcRenderer.send('drop', vx, vy),
  onWalk: (cb) => ipcRenderer.on('walk', (_e, on, dir, speed) => cb(!!on, dir, speed)),
  walkBusy: (b) => ipcRenderer.send('walk-busy', !!b),
  onPhys: (cb) => ipcRenderer.on('phys', (_e, state, impact) => cb(state, impact)),
  onPower: (cb) => ipcRenderer.on('power-state', (_e, p) => cb(p)),
  reportFps: (f) => ipcRenderer.send('perf-fps', f),
  chat: (text) => ipcRenderer.invoke('chat', text),
  tts: (text) => ipcRenderer.invoke('tts', text),
  libUrl: (kind, id) => ipcRenderer.invoke('lib-url', kind, id),
  onItemThumb: (cb) => ipcRenderer.on('item-thumb', (_e, id, key) => cb(id, key)),
  itemThumbDone: (id, url) => ipcRenderer.send('item-thumb-done', id, url),
  onItemRoll: (cb) => ipcRenderer.on('item-roll', (_e, speak) => cb(!!speak)),
  reportSpeaking: (on) => ipcRenderer.send('speaking-state', !!on),
  setIgnore: (ignore) => ipcRenderer.send('set-ignore', ignore),
  getPos: () => ipcRenderer.invoke('get-pos'),
  setPos: (x, y) => ipcRenderer.send('set-pos', x, y),
  contextMenu: () => ipcRenderer.send('context-menu'),
  onToggleChat: (cb) => ipcRenderer.on('toggle-chat', cb),
});
